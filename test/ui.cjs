const { launch, state, ready, nativeLayout, expand, expect } = require('./helpers.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  fs.mkdirSync(path.join(__dirname, '../work'), { recursive: true });
  const profile = fs.mkdtempSync(path.join(__dirname, '../work/ui-profile-'));
  const { app, shell, floating, business } = await launch(profile);
  try {
    assert.equal((await state(shell)).screen, 'connection');
    assert.equal((await state(shell)).status, 'idle');
    assert.ok((await nativeLayout(app)).children.filter(v => v.url !== shell.url()).every(v => !v.visible));
    await expect(shell.locator('h1')).toHaveText('Connect to a host');
    await shell.locator('#theme').selectOption('light');
    await expect.poll(() => shell.evaluate(() => matchMedia('(prefers-color-scheme: light)').matches)).toBe(true);
    assert.equal((await state(shell)).theme, 'light');
    await shell.reload();
    await expect(shell.locator('#theme')).toHaveValue('light');
    await assert.rejects(shell.evaluate(() => window.relay.action('theme', 'invalid')), /Unknown theme/);
    await expect(shell.locator('#host')).toHaveValue('example.com');
    await expect(shell.locator('#user')).toHaveValue('');
    await expect(shell.locator('#user')).toHaveAttribute('placeholder', require('node:os').userInfo().username);
    await shell.locator('#connect').click();
    assert.equal((await state(shell)).status, 'idle');
    assert.equal(await shell.locator('#path').evaluate(el => el.validity.valueMissing), true);
    await shell.locator('#path').fill('   ');
    await shell.locator('#connect').click();
    await expect(shell.locator('#error')).toHaveText('Enter a project path.');
    const rejected = await shell.evaluate(() => window.relay.action('connect', { mode: 'ssh', target: { host: 'example', port: 18765, path: '' } }));
    assert.match(rejected.error, /project path/);
    assert.equal(rejected.url, '');
    await shell.locator('#path').fill('/项目 with spaces/$(id);&?#');
    await shell.locator('#advanced').evaluate(el => { el.open = true; });
    await shell.locator('#mode').selectOption('local');
    // Health succeeds but the remote document fails: the local form must stay visible.
    await business.route('**/', route => route.abort('failed'));
    await shell.locator('#connect').click();
    await expect(shell.locator('#error')).toContainText('Workspace failed to load', { timeout: 15000 });
    assert.equal((await state(shell)).screen, 'connection');
    assert.equal((await state(shell)).url, '');
    await business.unroute('**/');
    await business.route('**/', route => route.fulfill({ status: 503, contentType: 'text/html', body: '<h1>Unavailable</h1>' }));
    await shell.locator('#connect').click();
    await expect(shell.locator('#error')).toContainText('HTTP 503', { timeout: 15000 });
    assert.equal((await state(shell)).screen, 'connection');
    await business.unroute('**/');
    // Hold the first document response; no workspace is exposed during this interval.
    let release;
    const held = new Promise(resolve => { release = resolve; });
    await business.route('**/', async route => { await held; await route.continue(); });
    await shell.locator('#connect').click();
    await expect.poll(async () => (await state(shell)).phase).toBe('loading');
    assert.equal((await state(shell)).screen, 'connection');
    assert.ok((await nativeLayout(app)).children.filter(v => v.url !== shell.url()).every(v => !v.visible));
    release(); await ready(shell); await business.unroute('**/');
    assert.equal((await state(shell)).pathReceived, true);
    assert.equal((await state(shell)).target.path, '/项目 with spaces/$(id);&?#');
    await expect(business.locator('#increment')).toBeVisible();
    await expect.poll(() => business.evaluate(() => matchMedia('(prefers-color-scheme: light)').matches)).toBe(true);
    await expand(floating);
    await floating.locator('#theme').selectOption('dark');
    await expect.poll(() => business.evaluate(() => matchMedia('(prefers-color-scheme: dark)').matches)).toBe(true);
    await expect(shell.locator('#theme')).toHaveValue('dark');
    await floating.locator('#collapse').click();
    let layout = await nativeLayout(app);
    const remote = layout.children.find(v => v.url?.startsWith('http:'));
    const card = layout.children.at(-1);
    assert.deepEqual(remote.bounds, { x: 0, y: 0, width: layout.size[0], height: layout.size[1] });
    assert.ok(card.url.endsWith('/floating.html') && card.visible);
    assert.equal(card.bounds.width, 56);
    assert.equal(card.bounds.height, 56);
    assert.equal(card.bounds.x + card.bounds.width, layout.size[0] - 16);
    assert.equal(card.bounds.y + card.bounds.height, layout.size[1] - 16);
    assert.deepEqual(await business.evaluate(() => [typeof require, typeof window.relay, typeof process]), ['undefined', 'undefined', 'undefined']);
    const prefs = await app.evaluate(({ webContents }) => webContents.getAllWebContents().filter(w => w.getURL().startsWith('http:')).map(w => w.getLastWebPreferences()));
    assert.ok(prefs.every(p => p.sandbox && p.contextIsolation && !p.nodeIntegration && !p.preload));
    await business.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await business.locator('.motion-demo span').evaluate(el => getComputedStyle(el).animationName), 'none');
    await business.emulateMedia({ reducedMotion: 'no-preference' });
    await business.locator('#delay').fill('3000'); await business.locator('#request').click();
    for (let i = 0; i < 5; i++) await business.locator('#increment').click();
    assert.equal(await business.locator('#count').innerText(), '05');
    assert.ok(await business.locator('#request').isDisabled());
    await expand(floating);
    await floating.locator('#collapse').focus();
    await floating.keyboard.press('Escape');
    await expect(floating.locator('#card')).toBeHidden();
    assert.equal((await nativeLayout(app)).children.at(-1).bounds.width, 56);
    // Probe the remote page next to the ball, inside the OLD expanded footprint.
    await business.evaluate(() => {
      const probe = document.createElement('button'); probe.id = 'hit-probe'; probe.textContent = '0';
      Object.assign(probe.style, { position: 'fixed', right: '90px', bottom: '30px', width: '120px', height: '44px', zIndex: '999' });
      probe.onclick = () => { probe.textContent = String(Number(probe.textContent) + 1); };
      document.body.append(probe);
    });
    await business.locator('#hit-probe').click();
    await expect(business.locator('#hit-probe')).toHaveText('1');
    await business.locator('#hit-probe').evaluate(el => el.remove());
    await expand(floating);
    await business.locator('#request-state').filter({ hasText: 'Done' }).waitFor();
    await floating.locator('#publish').click();
    await expect.poll(async () => (await state(shell)).version).toBe(2);
    await floating.locator('#refresh').click(); await ready(shell);
    await expect(business.locator('#page-version')).toHaveText('v2');
    await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await floating.locator('#stop').click();
    await expect(floating.locator('#status')).toHaveText('Connection lost');
    await floating.locator('#collapse').click();
    await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await floating.locator('#reconnect').click(); await ready(shell);
    await expect(business.locator('#page-version')).toHaveText('v2');
    await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await floating.locator('#disconnect').click();
    await expect(floating.locator('#status')).toHaveText('Disconnected');
    assert.equal((await state(shell)).screen, 'workspace');
    await floating.locator('#reconnect').click(); await ready(shell);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(800, 650));
    layout = await nativeLayout(app);
    assert.deepEqual(layout.children.find(v => v.url?.startsWith('http:')).bounds, { x: 0, y: 0, width: 800, height: 650 });
    assert.equal(layout.children.at(-1).bounds.x, 728);
    await expand(floating);
    const allowedURL = `${(await state(shell)).url}/`;
    await business.evaluate(() => { location.href = 'http://example.invalid/'; });
    assert.equal(await app.evaluate(({ webContents }) => webContents.getAllWebContents().find(w => w.getURL().startsWith('http:')).getURL()), allowedURL);
    await floating.locator('#switch').click();
    await expect.poll(async () => (await state(shell)).screen).toBe('connection');
    assert.equal((await state(shell)).status, 'idle');
    assert.ok((await nativeLayout(app)).children.filter(v => v.url !== shell.url()).every(v => !v.visible));
    console.log('PASS UI: 初始不自动连接、页面加载失败不收起、加载门控、全窗口业务页、默认56px原生视图/48px小球、展开/关闭/Escape收起、相邻远端点击、顶层右下角浮层、慢 API、发布刷新、断线重连、切换主机、窗口缩放、权限隔离');
  } finally { await app.close(); }
  const restarted = await launch(profile);
  try {
    await expect(restarted.shell.locator('#theme')).toHaveValue('dark');
    await expect.poll(() => restarted.shell.evaluate(() => matchMedia('(prefers-color-scheme: dark)').matches)).toBe(true);
    await restarted.shell.locator('#theme').selectOption('system');
    await expect.poll(() => restarted.app.evaluate(({ nativeTheme }) => nativeTheme.themeSource)).toBe('system');
  } finally { await restarted.app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
