// Explicit integration test: only the dedicated relay-demo.service is stopped/restarted.
const { launch, state, ready, nativeLayout, expand, expect } = require('./helpers.cjs');
const { execFileSync } = require('node:child_process');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { validateTarget, destination, localUsername } = require('../electron/connection.cjs');
let target;
const ssh = command => execFileSync('ssh', ['-p', String(target.sshPort), '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes', '-o', 'ConnectTimeout=8', destination(target), command], { encoding: 'utf8', timeout: 20000 }).trim();
(async () => {
  if (process.env.RUN_SSH_DEMO_TEST !== '1') throw new Error('Set RUN_SSH_DEMO_TEST=1 to opt in to restarting the dedicated demo service.');
  if (!process.env.RELAY_TEST_HOST || !process.env.RELAY_TEST_PATH) throw new Error('Set RELAY_TEST_HOST and RELAY_TEST_PATH for a dedicated test server.');
  target = validateTarget({ host: process.env.RELAY_TEST_HOST, path: process.env.RELAY_TEST_PATH,
    port: Number(process.env.RELAY_TEST_BACKEND_PORT || 18765), sshPort: Number(process.env.RELAY_TEST_SSH_PORT || 22), startService: true });
  target.user ||= localUsername();
  process.env.RELAY_SSH_HOST = target.host;
  process.env.RELAY_SSH_PORT = String(target.sshPort);
  process.env.RELAY_BACKEND_PORT = String(target.port);
  const profile = fs.mkdtempSync(path.join(__dirname, '../work/ssh-profile-'));
  let current = await launch(profile), passed = false;
  try {
    let { app, shell, floating, business } = current;
    assert.equal((await state(shell)).screen, 'connection');
    assert.equal((await state(shell)).status, 'idle');
    assert.equal((await state(shell)).history.length, 0);
    await shell.locator('#user').fill(target.user);
    await shell.locator('#path').fill(target.path);
    await shell.locator('#advanced').evaluate(el => { el.open = true; });
    await shell.locator('#ssh-port').fill(String(target.sshPort === 1 ? 2 : 1));
    await shell.locator('#connect').click();
    await expect.poll(async () => (await state(shell)).phase, { timeout: 20000 }).toBe('error');
    assert.equal((await state(shell)).screen, 'connection');
    assert.equal((await state(shell)).history.length, 0);
    assert.ok(await shell.locator('#error').isVisible());
    await shell.locator('#ssh-port').fill(String(target.sshPort));
    await shell.locator('#connect').click(); await ready(shell);
    assert.equal((await state(shell)).pathReceived, true);
    assert.equal((await state(shell)).target.path, target.path);
    const health = await (await fetch(`${(await state(shell)).url}/health`)).json();
    assert.equal(health.platform, 'linux');
    assert.equal(typeof health.hostname, 'string');
    assert.ok(health.hostname.length > 0);
    if (process.env.RELAY_TEST_HOSTNAME) assert.equal(health.hostname, process.env.RELAY_TEST_HOSTNAME);
    const layout = await nativeLayout(app);
    assert.deepEqual(layout.children.find(v => v.url?.startsWith('http:')).bounds, { x: 0, y: 0, width: layout.size[0], height: layout.size[1] });
    assert.ok(layout.children.at(-1).url.endsWith('/floating.html'));
    assert.equal(layout.children.at(-1).bounds.width, 56);
    await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await expect(floating.locator('#host-label')).toHaveText(destination(target));
    const saved = JSON.parse(fs.readFileSync(path.join(profile, 'connections.json'), 'utf8'));
    assert.equal(saved.length, 1);
    assert.deepEqual(Object.keys(saved[0]).sort(), ['host', 'user', 'path', 'lastConnected', 'port', 'sshPort', 'startService'].sort());
    await floating.locator('#switch').click();
    await expect.poll(async () => (await state(shell)).screen).toBe('connection');
    await expect(shell.locator('.history-item strong')).toHaveText(destination(target));
    await expect(shell.locator('.history-item small')).toHaveText(target.path);
    await shell.locator('#host').fill('different.example');
    await shell.locator('.history-item').click();
    await expect(shell.locator('#host')).toHaveValue(target.host);
    assert.equal((await state(shell)).status, 'idle'); // selection does not auto-connect
    await app.close();
    current = await launch(profile);
    ({ app, shell, floating, business } = current);
    assert.equal((await state(shell)).status, 'idle');
    await expect(shell.locator('.history-item')).toHaveCount(1);
    await expect(shell.locator('#host')).toHaveValue(target.host);
    await expect(shell.locator('#user')).toHaveValue(target.user);
    await expect(shell.locator('#path')).toHaveValue(target.path);
    await shell.locator('.history-item').click();
    await shell.locator('#connect').click(); await ready(shell);
    await expect(business.locator('#increment')).toBeVisible();
    await business.locator('#delay').fill('4000'); await business.locator('#request').click();
    for (let i = 0; i < 5; i++) await business.locator('#increment').click();
    assert.equal(await business.locator('#count').innerText(), '05');
    assert.ok(await business.locator('#request').isDisabled());
    await expand(floating);
    await expect(business.locator('#request-state')).toContainText('Done', { timeout: 8000 });
    ssh('systemctl --user stop relay-demo.service');
    await expect(floating.locator('#status')).toHaveText('Connection lost', { timeout: 7000 });
    assert.equal((await state(shell)).screen, 'workspace');
    await floating.locator('#collapse').click(); await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await business.locator('#increment').click();
    assert.equal(await business.locator('#count').innerText(), '06');
    await floating.locator('#reconnect').click(); await ready(shell);
    assert.equal(ssh('systemctl --user is-active relay-demo.service'), 'active');
    await expect(floating.locator('#launcher')).toBeVisible();
    await expand(floating);
    await floating.locator('#disconnect').click();
    await expect(floating.locator('#status')).toHaveText('Disconnected');
    await floating.locator('#reconnect').click(); await ready(shell);
    await expect(floating.locator('#launcher')).toBeVisible();
    assert.equal((await nativeLayout(app)).children.at(-1).bounds.width, 56);
    const finalState = await state(shell);
    await expect(business).toHaveURL(`${finalState.url}/`);
    const finalHealth = await (await fetch(`${finalState.url}/health`)).json();
    assert.equal(finalHealth.platform, 'linux');
    console.log('PASS REAL SSH: 初始连接页、SSH 失败可重试、真实远端全窗口加载、独立浮层、历史记录复用与重启持久化、慢 API 交互、远端停服/重启、断开/重连。');
    console.log(`LIVE_URL=${finalState.url}/`);
    passed = true;
  } finally {
    if (!passed) { try { ssh('systemctl --user start relay-demo.service'); } catch {} }
    await current.app.close().catch(() => {});
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
